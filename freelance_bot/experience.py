"""Требуемый стаж в тексте заказа или вакансии: «опыт коммерческой разработки от 3 лет» → 3.

Общий для скоринга (штраф за невыполнимый стаж) и самообучения (отметка «не мой уровень»
запоминает стаж из описания, ADR 0013). У вилки «1–3 года» требование — нижняя граница.
"""

from __future__ import annotations

import re

# «от 3 лет», «не менее 3-х лет», «3+ года», «1–3 года», «от 3 до 6 лет», «1,5 года»
_YEARS = (
    r"(?:(?:от|не\s+менее|не\s+меньше|более|свыше|минимум|min)\s*)?"
    r"(\d{1,2})(?:[,.]\d)?(?:\s*(?:[-–—]|до)\s*\d{1,2})?(?:-?х|-?и)?\s*\+?\s*(?:лет|года?)\b"
)
# Между «опыт» и числом — до 60 знаков без цифр и конца фразы: «опыт коммерческой
# разработки на Python — от 3 лет». Запятая тоже конец: «опыт не нужен, гарантия 3 года».
_GAP = r"[^\n.;!?,\d]{0,60}?"
_PATTERNS = (
    re.compile(rf"(?:опыт\w*|стаж\w*){_GAP}(?<![\w-]){_YEARS}"),
    # «от 3 лет коммерческой разработки», «3+ года опыта», «3 года работы»
    re.compile(
        rf"(?<![\w-]){_YEARS}\s+(?:(?:[а-яa-z-]+\s+){{0,2}}?(?:опыт|стаж|коммерческ)\w*|работы\b)"
    ),
    re.compile(r"(?<![\w-])(\d{1,2})\+?\s*(?:years?|yrs)\b(?:\s+of)?(?:\s+\w+){0,2}?\s+experience"),
    re.compile(r"experience[^\n.;!?\d]{0,40}?(?<![\w-])(\d{1,2})\+?\s*(?:years?|yrs)\b"),
)


def required_years(text: str) -> int | None:
    """Наибольший требуемый стаж в годах или None, если требования нет."""
    normalized = text.lower().replace("ё", "е")
    years = [int(m.group(1)) for pattern in _PATTERNS for m in pattern.finditer(normalized)]
    return max(years) if years else None


def years_word(n: int) -> str:
    """«от 1 года», «от 3 лет», «от 21 года» — после «от» нужен родительный падеж."""
    return "года" if n % 10 == 1 and n % 100 != 11 else "лет"
