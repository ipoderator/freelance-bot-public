def _topics(public: bool) -> tuple[tuple[str, str, str], ...]:
    return PUBLIC_TOPICS if public else OWNER_TOPICS


def description(public: bool) -> str:
    """Описание бота в Telegram; без публичного режима посторонним сказано, что он закрыт."""
    return DESCRIPTION if public else DESCRIPTION + PRIVATE_NOTE


def intro(public: bool) -> str:
    return PUBLIC_INTRO if public else OWNER_INTRO


def topic_text(
    public: bool, key: str, commands: Sequence[tuple[str, str]], when: str = "раз в час"
) -> str | None:
    """Раздел справки; неизвестный ключ (старая кнопка) — None."""
    for name, _, text in _topics(public):
        if name == key:
            listed = "\n".join(f"/{c} — {esc(about)}" for c, about in commands)
            return text.replace("{when}", esc(when)).replace("{commands}", listed)
    return None


def keyboard(public: bool, current: str = "") -> list[list[tuple[str, str]]]:
    """Темы по две в ряд; в разделе — ещё «Оглавление», текущая тема не повторяется."""
    buttons = [(label, PREFIX + key) for key, label, _ in _topics(public) if key != current]
    rows = [buttons[i : i + 2] for i in range(0, len(buttons), 2)]
    if current:
        rows.append([(BACK, PREFIX + "intro")])
    return rows
